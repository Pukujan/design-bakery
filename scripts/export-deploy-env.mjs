#!/usr/bin/env node
/**
 * Export additionals/deploy/railway.env and additionals/deploy/vercel.env from local backend/.env + frontend/.env.
 * Usage: node scripts/export-deploy-env.mjs
 * Files are gitignored — do not commit.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i <= 0) continue;
    out[t.slice(0, i).trim()] = t.slice(i + 1).trim();
  }
  return out;
}

function lines(obj) {
  return Object.entries(obj)
    .filter(([, v]) => v !== undefined && v !== '')
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');
}

const b = parseEnv(readFileSync(resolve(root, 'backend/.env'), 'utf8'));
const f = parseEnv(readFileSync(resolve(root, 'frontend/.env'), 'utf8'));

const railwayHeader = `# Railway — Variables → Raw Editor (paste all)
# After deploy: confirm GET https://YOUR-RAILWAY-URL/health
# Replace YOUR-RAILWAY-URL in additionals/deploy/vercel.env too

`;

const railwayVars = {
  OPENROUTER_API_KEY: b.OPENROUTER_API_KEY,
  OPENROUTER_MODEL: b.OPENROUTER_MODEL || 'deepseek/deepseek-chat-v3.1',
  OPENROUTER_IMAGE_MODEL: b.OPENROUTER_IMAGE_MODEL || 'google/gemini-2.5-flash-image',
  SUPABASE_URL: b.SUPABASE_URL,
  SUPABASE_SERVICE_ROLE_KEY: b.SUPABASE_SERVICE_ROLE_KEY,
  SUPABASE_STORAGE_BUCKET: b.SUPABASE_STORAGE_BUCKET || 'design-bakery',
  IMAGE_STORAGE: 'supabase',
  CONTENT_BACKEND: 'supabase',
  ADMIN_JWT_SECRET: b.ADMIN_JWT_SECRET,
  ADMIN_EMAIL: b.ADMIN_EMAIL,
  ADMIN_PASSWORD: b.ADMIN_PASSWORD,
  ALLOWED_ORIGINS: 'https://www.design-bakery.com,https://design-bakery.com',
  ALLOWED_ADMIN_EMAILS: b.ALLOWED_ADMIN_EMAILS,
  PUBLISH_KIT_VISUAL_MODE: b.PUBLISH_KIT_VISUAL_MODE || 'template',
};

const vercelHeader = `# Vercel — Settings → Environment Variables → Import .env (Production)
# Set VITE_BLOG_API_URL after Railway gives you a domain
# VITE_SUPABASE_* = fast public blog reads (anon key from Supabase Dashboard → API)

`;

const vercelVars = {
  VITE_ENABLE_BLOG_PUBLISH_KIT: 'true',
  VITE_BLOG_API_URL: 'https://YOUR-RAILWAY-URL.up.railway.app',
  VITE_CONTENT_BACKEND: 'supabase',
  VITE_SUPABASE_URL: f.VITE_SUPABASE_URL,
  VITE_SUPABASE_ANON_KEY: f.VITE_SUPABASE_ANON_KEY,
};

mkdirSync(resolve(root, 'deploy'), { recursive: true });
writeFileSync(
  resolve(root, 'additionals/deploy/railway.env'),
  railwayHeader + lines(railwayVars) + '\n',
);
writeFileSync(
  resolve(root, 'additionals/deploy/vercel.env'),
  vercelHeader + lines(vercelVars) + '\n',
);
writeFileSync(
  resolve(root, 'additionals/deploy/README.md'),
  `# Deploy env exports (local only — gitignored)

Generated by \`node scripts/export-deploy-env.mjs\` from \`backend/.env\` + \`frontend/.env\`.

| File | Upload to |
|------|-----------|
| \`railway.env\` | Railway → service → **Variables** → **Raw Editor** → paste |
| \`vercel.env\` | Vercel → project → **Settings** → **Environment Variables** → **Import .env** → Production |

## After Railway first deploy

1. Copy Railway public URL (no trailing slash).
2. Edit \`vercel.env\`: set \`VITE_BLOG_API_URL=https://…\`
3. Re-import on Vercel or edit that one var → **Redeploy**.

## Security

These files contain secrets. Never commit or push them.
`,
);

console.log('Created additionals/deploy/railway.env');
console.log('Created additionals/deploy/vercel.env');
console.log('Created additionals/deploy/README.md');
