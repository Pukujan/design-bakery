#!/usr/bin/env node
/**
 * Builds packages/cover-studio-kit/export-bundle/ — self-contained copy for another repo.
 * Usage: pnpm run export:cover-studio
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const kitRoot = join(root, 'packages/cover-studio-kit');
const outRoot = join(kitRoot, 'export-bundle');
const manifest = JSON.parse(readFileSync(join(kitRoot, 'export-manifest.json'), 'utf8'));

function copy(src, dest) {
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(src, dest, { recursive: true, force: true });
}

function copyFile(srcRel, destRel) {
  const src = join(root, srcRel);
  const dest = join(outRoot, destRel);
  copy(src, dest);
  console.log(`  ${srcRel} → ${destRel}`);
}

console.log('[export:cover-studio] Cleaning export-bundle…');
rmSync(outRoot, { recursive: true, force: true });
mkdirSync(outRoot, { recursive: true });

console.log('[export:cover-studio] Copying cover-studio-kit package…');
const kitSkip = new Set(['export-bundle', 'node_modules']);
for (const name of ['src', 'docs', 'examples', 'package.json', 'tsconfig.json', 'README.md', 'EXPORT.md', 'export-manifest.json']) {
  const src = join(kitRoot, name);
  const dest = join(outRoot, 'packages/cover-studio-kit', name);
  copy(src, dest);
}

console.log('[export:cover-studio] Copying Express API…');
for (const rel of manifest.server.api) {
  copyFile(rel, rel);
}

console.log('[export:cover-studio] Copying services engine…');
const svc = manifest.server.services;
copyFile(svc.resolveBlogPost, svc.resolveBlogPost);
copyFile(svc.agentJson, svc.agentJson);
copyFile(svc.openrouter, svc.openrouter);
copyFile(svc.openrouterVision, svc.openrouterVision);
copyFile(svc.apiError, svc.apiError);
copyFile(svc.supabaseClient, svc.supabaseClient);
copyFile(join(svc.publishKit, ''), join(svc.publishKit, ''));
copyFile(join(svc.coverStudio, ''), join(svc.coverStudio, ''));
copyFile(join(svc.media, ''), join(svc.media, ''));

console.log('[export:cover-studio] Copying services build config…');
for (const rel of manifest.server.build) {
  copyFile(rel, rel);
}

console.log('[export:cover-studio] Copying Supabase migrations…');
for (const rel of manifest.supabase) {
  copyFile(rel, rel);
}

console.log('[export:cover-studio] Writing env examples…');
mkdirSync(join(outRoot, 'backend'), { recursive: true });
mkdirSync(join(outRoot, 'frontend'), { recursive: true });
writeFileSync(
  join(outRoot, 'backend/.env.example'),
  readFileSync(join(kitRoot, 'templates/backend.env.example'), 'utf8'),
);
writeFileSync(
  join(outRoot, 'frontend/.env.example'),
  readFileSync(join(kitRoot, 'templates/frontend.env.example'), 'utf8'),
);

writeFileSync(
  join(outRoot, 'EXPORT_STAMP.txt'),
  `Cover Studio export bundle\nGenerated: ${new Date().toISOString()}\nSource: design-bakery\n`,
);

writeFileSync(
  join(outRoot, 'README.md'),
  `# Cover Studio export bundle

Self-contained copy generated by \`pnpm run export:cover-studio\` from design-bakery.

## Quick start

1. Copy this entire folder into your new repo.
2. Read \`packages/cover-studio-kit/README.md\` (full history, architecture, roadmap).
3. \`cd backend/services && pnpm install && pnpm run build\`
4. Run migrations in \`supabase/migrations/\` (003–008) in Supabase SQL editor.
5. Copy \`backend/.env.example\` → \`backend/.env\` and fill secrets.
6. Start API: \`pnpm exec tsx packages/cover-studio-kit/examples/standalone-server.ts\`
7. Wire client: \`PublicCoverStudioApp\` from \`@design-bakery/cover-studio-kit/client\`

## Public (non-admin) app

Use \`PublicCoverStudioApp\` — same indigo UI as design-bakery admin Cover Studio, no AdminLayout.

See \`packages/cover-studio-kit/examples/public-vite-app/App.example.tsx\`.

## Docs

| File | Contents |
|------|----------|
| \`packages/cover-studio-kit/README.md\` | Main guide |
| \`packages/cover-studio-kit/docs/HISTORY.md\` | Full audit log |
| \`packages/cover-studio-kit/docs/ROADMAP.md\` | Cache-first matching plan |
| \`packages/cover-studio-kit/docs/ARCHITECTURE.md\` | Module boundaries |
| \`packages/cover-studio-kit/EXPORT.md\` | File-level copy list |

Generated: ${new Date().toISOString()}
`,
);

console.log(`[export:cover-studio] Done → ${relative(root, outRoot)}/`);
